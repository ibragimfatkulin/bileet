export function matchFaq(text: string): string {
  const q = text.toLowerCase().trim();
  if (!q) {
    return "Задайте вопрос или выберите тему ниже — я подскажу по правилам bileet.";
  }
  for (const item of FAQ_ITEMS) {
    if (item.keywords.some((kw) => q.includes(kw))) {
      return item.answer;
    }
  }
  return "Я помощник bileet по частым вопросам. Попробуйте спросить про возврат, оплату, время прихода, детский тариф, лимит мест или письмо с билетом.";
}
